/// ISO-8859-1 → EBCDIC CP037 (inverse table, computed at compile time).
pub const LATIN1_TO_EBCDIC: [u8; 256] = invert(&EBCDIC_TO_LATIN1);

const fn invert(table: &[u8; 256]) -> [u8; 256] {
    let mut out = [0u8; 256];
    let mut i = 0;
    while i < 256 {
        out[table[i] as usize] = i as u8;
        i += 1;
    }
    out
}

/// Translate EBCDIC bytes to ISO-8859-1 in place.
pub fn to_latin1(buf: &mut [u8]) {
    for b in buf {
        *b = EBCDIC_TO_LATIN1[*b as usize];
    }
}

/// Translate ISO-8859-1 bytes to EBCDIC in place.
pub fn to_ebcdic(buf: &mut [u8]) {
    for b in buf {
        *b = LATIN1_TO_EBCDIC[*b as usize];
    }
}

/// Length of the pre-connection message.
pub const PRECONNECT_LEN: usize = 24;

/// `"PESIT   "` in EBCDIC.
pub const PRECONNECT_MAGIC: [u8; 8] = [0xD7, 0xC5, 0xE2, 0xC9, 0xE3, 0x40, 0x40, 0x40];
/// `"ACK0"` in EBCDIC.
pub const PRECONNECT_ACK: [u8; 4] = [0xC1, 0xC3, 0xD2, 0xF0];
/// `"NAK0"` in EBCDIC.
pub const PRECONNECT_NAK: [u8; 4] = [0xD5, 0xC1, 0xD2, 0xF0];

/// Build the 24-byte EBCDIC pre-connection message:
/// `"PESIT   "` + identifier (8, blank padded) + password (8, blank padded).
#[must_use]
pub fn preconnect_message(identifier: &str, password: &str) -> [u8; PRECONNECT_LEN] {
    let mut msg = [0x40u8; PRECONNECT_LEN];
    msg[..8].copy_from_slice(&PRECONNECT_MAGIC);
    for (dst, src) in msg[8..16].iter_mut().zip(identifier.bytes().take(8)) {
        *dst = LATIN1_TO_EBCDIC[src as usize];
    }
    for (dst, src) in msg[16..24].iter_mut().zip(password.bytes().take(8)) {
        *dst = LATIN1_TO_EBCDIC[src as usize];
    }
    msg
}

/// Whether `data` starts with an EBCDIC pre-connection message.
#[must_use]
pub fn is_preconnect(data: &[u8]) -> bool {
    data.len() >= 5 && data[..5] == PRECONNECT_MAGIC[..5]
}

/// Decode a pre-connection message into `(identifier, password)` (trimmed).
#[must_use]
pub fn parse_preconnect(data: &[u8]) -> Option<(String, String)> {
    if !is_preconnect(data) || data.len() < PRECONNECT_LEN {
        return None;
    }
    let field = |range: std::ops::Range<usize>| {
        data[range]
            .iter()
            .map(|b| char::from(EBCDIC_TO_LATIN1[*b as usize]))
            .collect::<String>()
            .trim_end()
            .to_owned()
    };
    Some((field(8..16), field(16..24)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_inverse() {
        for i in 0..=255u8 {
            assert_eq!(LATIN1_TO_EBCDIC[EBCDIC_TO_LATIN1[i as usize] as usize], i);
        }
        assert_eq!(LATIN1_TO_EBCDIC[b'A' as usize], 0xC1);
        assert_eq!(LATIN1_TO_EBCDIC[b' ' as usize], 0x40);
        assert_eq!(LATIN1_TO_EBCDIC[b'0' as usize], 0xF0);
    }

    #[test]
    fn preconnect_round_trip() {
        let m = preconnect_message("PWSRV01", "");
        assert_eq!(&m[..8], &PRECONNECT_MAGIC);
        assert!(is_preconnect(&m));
        assert_eq!(
            parse_preconnect(&m),
            Some(("PWSRV01".into(), String::new()))
        );
        let m = preconnect_message("CETOM1", "secret");
        assert_eq!(
            parse_preconnect(&m),
            Some(("CETOM1".into(), "secret".into()))
        );
        let mut ack = b"ACK0".to_vec();
        to_ebcdic(&mut ack);
        assert_eq!(ack, PRECONNECT_ACK);
        let mut nak = b"NAK0".to_vec();
        to_ebcdic(&mut nak);
        assert_eq!(nak, PRECONNECT_NAK);
    }
}
